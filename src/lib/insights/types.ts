// -------------- INSIGHTS — CONTENT TYPES --------------
// Portable block structure for article bodies. Inline links and bold inside
// text strings use [label](href) and **bold** markdown-style syntax and are
// parsed at render time (see components/insights/InsightBlocks.tsx).

/** In-body editorial figures rendered by components/insights/InsightFigure.tsx. */
export type InsightFigureKind =
  'same-pages-different-scope' | 'ownership-layers' | 'three-architectures';

export type InsightBlock =
  | { t: 'p'; x: string }
  | { t: 'figure'; x: InsightFigureKind; caption?: string }
  | { t: 'h2'; x: string }
  | { t: 'h3'; x: string }
  | { t: 'ul'; x: string[] }
  | { t: 'quote'; x: string }
  | { t: 'callout'; title: string; x: string }
  | { t: 'table'; headers: string[]; rows: string[][] }
  | { t: 'code'; x: string }
  | { t: 'img'; src?: string | null; alt?: string; caption?: string };

export type InsightCta = {
  title: string;
  text: string;
  label: string;
  href: string;
};

/** The one commercial service page an article most naturally leads to. */
export type InsightRelatedService = {
  /** Descriptive anchor text, e.g. 'Explore Shopify development'. */
  label: string;
  href: string;
  /** One sentence on why the service is relevant to this article. */
  note: string;
};

/**
 * Original cover artwork for an article. Both files are static SVGs under
 * public/static/insights/art, generated by scripts/generate-insight-art.mjs:
 * `cover` is 3:2 (cards, related reading, the mobile hero) and `wide` is
 * 5:2 (the article hero from the md breakpoint). One alt text describes the
 * composition; it is shared because both crops show the same picture.
 */
export type InsightArt = {
  cover: string;
  wide: string;
  alt: string;
};

/** Intrinsic dimensions of the two art crops — fixed by the generator. */
export const INSIGHT_ART_SIZES = {
  cover: { width: 1200, height: 800 },
  wide: { width: 1600, height: 640 },
} as const;

/** An article as authored — reading time is computed, not stored. */
export type InsightArticleSource = {
  slug: string;
  title: string;
  seoTitle: string;
  metaDescription: string;
  excerpt: string;
  /**
   * Short direct answer shown immediately after the header — the article's
   * conclusion in one or two sentences, for readers who skim.
   */
  summary?: string;
  category: string;
  /**
   * Topic tags: the subjects an article genuinely covers, used as the
   * "Topics" facet and as a search field. Human-readable; slugs are derived.
   */
  tags?: string[];
  /** ISO publish date, e.g. '2026-06-30'. */
  date: string;
  /** ISO date of the last significant update, if any. */
  updated?: string;
  /** Drafts (false) must never render anywhere. */
  published: boolean;
  art?: InsightArt;
  blocks: InsightBlock[];
  cta?: InsightCta;
  relatedService?: InsightRelatedService;
};

/** An article as consumed by pages: source data + computed reading time. */
export type InsightArticle = InsightArticleSource & {
  /** Computed reading time: ceil(words / 225), minimum 1. */
  readMins: number;
};

export type InsightCategory = {
  name: string;
  slug: string;
  count: number;
};

/** A topic tag with its published-article count. */
export type InsightTopic = {
  name: string;
  slug: string;
  count: number;
};

/**
 * Reading-time bucket. Buckets are a fixed scale; only buckets that contain
 * published articles are ever offered as a filter.
 */
export type InsightReadBucket = {
  slug: 'quick' | 'medium' | 'deep';
  label: string;
  hint: string;
  count: number;
};

/**
 * The listing shape — everything the index, cards and the discovery system
 * need, and nothing else. Serialisable (crosses the server/client boundary).
 */
export type InsightSummary = {
  slug: string;
  title: string;
  excerpt: string;
  summary?: string;
  category: string;
  categorySlug: string;
  tags: string[];
  tagSlugs: string[];
  date: string;
  updated?: string;
  readMins: number;
  readBucket: InsightReadBucket['slug'];
  /** h2 and h3 headings, in order — searchable, and shown as match context. */
  headings: string[];
  art?: InsightArt;
};
